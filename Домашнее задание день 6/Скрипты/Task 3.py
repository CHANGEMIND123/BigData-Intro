# Использовал try-except по той же причине.
try:
    temp = float(input("Введите температуру в градусах Цельсия: ")) #Преобразовал строку в тип float для температуры.
except ValueError:
    print("Ошибка! Можно вводить только числа и цифры, буквы и символы запрещены.")

Fahrenheit = temp * 9 / 5 + 32

print (f"{temp}°C это {Fahrenheit}°F")