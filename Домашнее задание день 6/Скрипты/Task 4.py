# По такой же причине юзал try-except, как и в прошлых заданиях.
try:
    inp = int(input("Введите целое число: "))
except ValueError:
    print("Ошибка! Введите целое число, буквы и символы запрещены.")
    exit()

if inp % 2 == 0:
    print(f"Число {inp} - чётное")

else:
    print (f"Число {inp} - нечётное.")